def ring42_matmul(A, B):
    """
    Batched 3x3 matrix multiplication over F_7[x]/(x^42 - 1).
    
    Args:
        A, B: int32 tensors of shape (63, batch)
              Layout: entry e (0-8), component c (0-6) at index e*7 + c
    Returns:
        C: int32 tensor of shape (63, batch)
    """
    assert A.shape[0] == 63 and B.shape[0] == 63
    batch_size = A.shape[1]
    C = torch.empty_like(A)
    grid = lambda meta: (triton.cdiv(batch_size, meta['BLOCK_SIZE']),)
    ring42_matmul_kernel[grid](A, B, C, n_matrices=batch_size, BLOCK_SIZE=128)
    return C


# --- Reference Implementation ---
def _mod7(x): return int(x) % 7

def _pack_poly(coeffs):
    c0, c1, c2, c3, c4, c5 = coeffs
    return c0 | (c1 << 3) | (c2 << 6) | (c3 << 9) | (c4 << 12) | (c5 << 15)

def _unpack_poly(packed):
    mask = 7
    return [packed & mask, (packed >> 3) & mask, (packed >> 6) & mask,
            (packed >> 9) & mask, (packed >> 12) & mask, (packed >> 15) & mask]

def _dft6(c):
    c0, c1, c2, c3, c4, c5 = c
    return [_mod7(c0 + c1 + c2 + c3 + c4 + c5),
            _mod7(c0 + c1*3 + c2*2 + c3*6 + c4*4 + c5*5),
            _mod7(c0 + c1*2 + c2*4 + c3 + c4*2 + c5*4),
            _mod7(c0 + c1*6 + c2 + c3*6 + c4 + c5*6),
            _mod7(c0 + c1*4 + c2*2 + c3 + c4*4 + c5*2),
            _mod7(c0 + c1*5 + c2*4 + c3*6 + c4*2 + c5*3)]

def _idft6(f):
    f0, f1, f2, f3, f4, f5 = f
    t = [_mod7(f0 + f1 + f2 + f3 + f4 + f5),
         _mod7(f0 + f1*5 + f2*4 + f3*6 + f4*2 + f5*3),
         _mod7(f0 + f1*4 + f2*2 + f3 + f4*4 + f5*2),
         _mod7(f0 + f1*6 + f2 + f3*6 + f4 + f5*6),
         _mod7(f0 + f1*2 + f2*4 + f3 + f4*2 + f5*4),
         _mod7(f0 + f1*3 + f2*2 + f3*6 + f4*4 + f5*5)]
    return [_mod7(x * 6) for x in t]

def _ring42_mul_freq(a, b, omega):
    """Multiply two ring42 elements at a single frequency."""
    h = []
    for k in range(7):
        direct = 0
        wrap = 0
        for i in range(7):
            j = k - i
            if 0 <= j < 7:
                direct += a[i] * b[j]
            j = k + 7 - i
            if 0 <= j < 7:
                wrap += a[i] * b[j]
        h.append(_mod7(direct + omega * wrap))
    return h

def _ring42_mul(f, g):
    """Multiply two elements of F_7[x]/(x^42-1), each represented as 7 polys in F_7[y]/(y^6-1)."""
    # DFT all components
    f_dft = [_dft6(f[c]) for c in range(7)]
    g_dft = [_dft6(g[c]) for c in range(7)]
    # Reorganize: f_freq[freq][component]
    f_freq = [[f_dft[c][freq] for c in range(7)] for freq in range(6)]
    g_freq = [[g_dft[c][freq] for c in range(7)] for freq in range(6)]
    omega_powers = [1, 3, 2, 6, 4, 5]
    # Multiply at each frequency
    h_freq = []
    for freq in range(6):
        h_freq.append(_ring42_mul_freq(f_freq[freq], g_freq[freq], omega_powers[freq]))
    # IDFT to get result: h[component][coefficient]
    h = []
    for c in range(7):
        freq_vals = [h_freq[freq][c] for freq in range(6)]
        h.append(_idft6(freq_vals))
    return h

def ring42_matmul_reference(A, B):
    """Reference implementation for testing."""
    import numpy as np
    is_torch = torch.is_tensor(A)
    if is_torch:
        A, B = A.cpu().numpy(), B.cpu().numpy()
    batch = A.shape[1]
    C = np.empty((63, batch), dtype=np.int32)
    
    for b_idx in range(batch):
        # Extract matrices: a_mat[entry][component] = list of 6 coefficients
        a_mat = [[_unpack_poly(int(A[e*7 + c, b_idx])) for c in range(7)] for e in range(9)]
        b_mat = [[_unpack_poly(int(B[e*7 + c, b_idx])) for c in range(7)] for e in range(9)]
        
        # Matrix multiply: C[row,col] = sum_k A[row,k] * B[k,col]
        c_mat = [[None] * 7 for _ in range(9)]
        for row in range(3):
            for col in range(3):
                c_entry = row * 3 + col
                # Accumulate 3 products
                acc = [[0]*6 for _ in range(7)]
                for k in range(3):
                    a_entry = row * 3 + k
                    b_entry = k * 3 + col
                    prod = _ring42_mul(a_mat[a_entry], b_mat[b_entry])
                    for comp in range(7):
                        for coef in range(6):
                            acc[comp][coef] = _mod7(acc[comp][coef] + prod[comp][coef])
                for comp in range(7):
                    c_mat[c_entry][comp] = acc[comp]
        
        # Pack and store
        for e in range(9):
            for c in range(7):
                C[e*7 + c, b_idx] = _pack_poly(c_mat[e][c])
    
    return torch.from_numpy(C) if is_torch else C


