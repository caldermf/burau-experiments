    start = time.perf_counter()
    for _ in range(n_iters):
        _ = ring42_matmul(A, B)
    torch.cuda.synchronize()
    elapsed = time.perf_counter() - start
    
    mats_per_sec = batch_size * n_iters / elapsed
    print(f'Throughput: {mats_per_sec:.2e} matrix multiplications/sec')
    print(f'Time per batch of {batch_size}: {elapsed/n_iters*1000:.3f} ms')


