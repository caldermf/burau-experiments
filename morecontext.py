@triton.jit
def fast_mod7(x):
    q = (x.to(tl.int64) * 74899) >> 19
    q = q.to(tl.int32)
    r = x - q * 7
    r = tl.where(r >= 7, r - 7, r)
    r = tl.where(r < 0, r + 7, r)
    return r

@triton.jit
def unpack_poly(packed):
    mask = 7
    return (packed & mask, (packed >> 3) & mask, (packed >> 6) & mask,
            (packed >> 9) & mask, (packed >> 12) & mask, (packed >> 15) & mask)

@triton.jit
def pack_poly(c0, c1, c2, c3, c4, c5):
    return c0 | (c1 << 3) | (c2 << 6) | (c3 << 9) | (c4 << 12) | (c5 << 15)

@triton.jit
def dft6(c0, c1, c2, c3, c4, c5):
    f0 = fast_mod7(c0 + c1 + c2 + c3 + c4 + c5)
    f1 = fast_mod7(c0 + c1*3 + c2*2 + c3*6 + c4*4 + c5*5)
    f2 = fast_mod7(c0 + c1*2 + c2*4 + c3 + c4*2 + c5*4)
    f3 = fast_mod7(c0 + c1*6 + c2 + c3*6 + c4 + c5*6)
    f4 = fast_mod7(c0 + c1*4 + c2*2 + c3 + c4*4 + c5*2)
    f5 = fast_mod7(c0 + c1*5 + c2*4 + c3*6 + c4*2 + c5*3)
    return f0, f1, f2, f3, f4, f5

@triton.jit
def idft6(f0, f1, f2, f3, f4, f5):
    t0 = fast_mod7(f0 + f1 + f2 + f3 + f4 + f5)
    t1 = fast_mod7(f0 + f1*5 + f2*4 + f3*6 + f4*2 + f5*3)
    t2 = fast_mod7(f0 + f1*4 + f2*2 + f3 + f4*4 + f5*2)
    t3 = fast_mod7(f0 + f1*6 + f2 + f3*6 + f4 + f5*6)
    t4 = fast_mod7(f0 + f1*2 + f2*4 + f3 + f4*2 + f5*4)
    t5 = fast_mod7(f0 + f1*3 + f2*2 + f3*6 + f4*4 + f5*5)
    return fast_mod7(t0*6), fast_mod7(t1*6), fast_mod7(t2*6), fast_mod7(t3*6), fast_mod7(t4*6), fast_mod7(t5*6)

@triton.jit
def ring42_mul_freq(a0, a1, a2, a3, a4, a5, a6, b0, b1, b2, b3, b4, b5, b6, omega):
    # h_k = sum_{i+j=k} a_i*b_j + omega * sum_{i+j=k+7} a_i*b_j
    # k=0: direct (0,0); wrap (1,6),(2,5),(3,4),(4,3),(5,2),(6,1)
    h0 = fast_mod7(a0*b0 + omega*(a1*b6 + a2*b5 + a3*b4 + a4*b3 + a5*b2 + a6*b1))
    # k=1: direct (0,1),(1,0); wrap (2,6),(3,5),(4,4),(5,3),(6,2)
    h1 = fast_mod7(a0*b1 + a1*b0 + omega*(a2*b6 + a3*b5 + a4*b4 + a5*b3 + a6*b2))
    # k=2: direct (0,2),(1,1),(2,0); wrap (3,6),(4,5),(5,4),(6,3)
    h2 = fast_mod7(a0*b2 + a1*b1 + a2*b0 + omega*(a3*b6 + a4*b5 + a5*b4 + a6*b3))
    # k=3: direct (0,3),(1,2),(2,1),(3,0); wrap (4,6),(5,5),(6,4)
    h3 = fast_mod7(a0*b3 + a1*b2 + a2*b1 + a3*b0 + omega*(a4*b6 + a5*b5 + a6*b4))
    # k=4: direct (0,4),(1,3),(2,2),(3,1),(4,0); wrap (5,6),(6,5)
    h4 = fast_mod7(a0*b4 + a1*b3 + a2*b2 + a3*b1 + a4*b0 + omega*(a5*b6 + a6*b5))
    # k=5: direct (0,5),(1,4),(2,3),(3,2),(4,1),(5,0); wrap (6,6)
    h5 = fast_mod7(a0*b5 + a1*b4 + a2*b3 + a3*b2 + a4*b1 + a5*b0 + omega*(a6*b6))
    # k=6: direct (0,6),(1,5),(2,4),(3,3),(4,2),(5,1),(6,0); wrap: none
    h6 = fast_mod7(a0*b6 + a1*b5 + a2*b4 + a3*b3 + a4*b2 + a5*b1 + a6*b0)
    return h0, h1, h2, h3, h4, h5, h6

