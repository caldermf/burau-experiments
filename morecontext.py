    B_small = B[:, :8].clone()
    
    C_ref = ring42_matmul_reference(A_small, B_small)
    C_triton = ring42_matmul(A_small, B_small)
    
    if torch.equal(C_ref.cuda(), C_triton):
        print('Correctness test passed!')
    else:
        print('Correctness test FAILED!')
