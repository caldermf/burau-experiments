# @title Default title text
def generate_samples(starting_vector, Apower, Bpower,samples_per_length,length_bound):

  starting_vector = np.array(starting_vector, dtype=matrix_dtype)
  bucket = np.tile(starting_vector, (samples_per_length, 1))

  print(f'starting_vector = {bucket[0]}')

  A_samples = np.zeros((samples_per_length*length_bound,Apower.shape[-1]),dtype=matrix_dtype)
  B_samples = np.zeros((samples_per_length*length_bound,Apower.shape[-1]),dtype=matrix_dtype)

  number_of_A_powers = Apower.shape[0]
  number_of_B_powers = Bpower.shape[0]

  for c in range(length_bound):

    # do Bs

    samples = np.einsum('bij, cj -> bci', Bpower, bucket).reshape(-1,3)
    samples = samples / (np.sum(samples**2,axis=-1)**(1/2)).reshape(-1,1)

    scores = np.min(np.arccos(np.abs(samples)),axis=-1)**2 # list of distances to nearest eigenvector (or its negative)

    probabilities = (scores / np.sum(scores)).astype(np.float64)
    sampled_indices = np.random.choice(len(samples), size=samples_per_length, p=probabilities, replace=True)
    bucket = samples[sampled_indices]

    B_samples[c*samples_per_length:(c+1)*samples_per_length] = bucket

    samples = np.einsum('bij, cj -> bci', Apower, bucket).reshape(-1,3)
    samples = samples / (np.sum(samples**2,axis=-1)**(1/2)).reshape(-1,1)

    scores = np.min(np.arccos(np.abs(samples)),axis=-1)**2 # list of distances to nearest eigenvector (or its negative)

    probabilities = (scores / np.sum(scores)).astype(np.float64)
    sampled_indices = np.random.choice(len(samples), size=samples_per_length, p=probabilities, replace=True)
    bucket = samples[sampled_indices]

    A_samples[c*samples_per_length:(c+1)*samples_per_length] = bucket

  return A_samples, B_samples

