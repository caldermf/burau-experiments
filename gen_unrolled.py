#!/usr/bin/env python3
"""
Generate the explicit Triton kernel for ring matmul (F_7[x]/(x^6-1), 3x3, SoA).
Run: python gen_unrolled.py          # print to stdout
     python gen_unrolled.py -o unrolled.py  # write to file

The generator uses normal Python (lists, loops, indexing); the *output* is
the fully unrolled code Triton requires. Change N_ENTRIES, N_FREQ, or matmul
layout here and regenerate.
"""
from __future__ import annotations

import argparse

# --- Spec (readable, generalizable) ---
N_ENTRIES = 9   # 3x3 matrix flattened
N_FREQ = 6      # degree 6 polynomial
# C[i] = sum over k of A[row(i),k] * B[k,col(i)]; row(i)=i//3, col(i)=i%3
# So C_ij = sum_k A_ik B_kj  -> entry index i*3+j, so row*3+col
def matmul_operands(c_entry: int) -> list[tuple[int, int]]:
    """For output entry c (0..8), return list of (a_entry, b_entry) for C = A@B."""
    row, col = c_entry // 3, c_entry % 3
    return [(row * 3 + k, k * 3 + col) for k in range(3)]


def generate_kernel_body() -> str:
    lines = []

    # 1. LOAD (SoA)
    lines.append("    # --- 1. LOAD (SoA) ---")
    for i in range(N_ENTRIES):
        lines.append(f"    a{i} = tl.load(A_ptr + {i} * n_matrices + offs, mask=mask, other=0)")
    for i in range(N_ENTRIES):
        lines.append(f"    b{i} = tl.load(B_ptr + {i} * n_matrices + offs, mask=mask, other=0)")

    # 2. UNPACK & DFT
    lines.append("")
    lines.append("    # --- 2. UNPACK & DFT for each of 9 entries ---")
    for i in range(N_ENTRIES):
        c_vars = ", ".join(f"a{i}_c{j}" for j in range(N_FREQ))
        lines.append(f"    {c_vars} = unpack_poly(a{i})")
        af_vars = ", ".join(f"af{i}_{j}" for j in range(N_FREQ))
        cf_vars = ", ".join(f"a{i}_c{j}" for j in range(N_FREQ))
        lines.append(f"    {af_vars} = dft_6_point({cf_vars})")
    for i in range(N_ENTRIES):
        c_vars = ", ".join(f"b{i}_c{j}" for j in range(N_FREQ))
        lines.append(f"    {c_vars} = unpack_poly(b{i})")
        bf_vars = ", ".join(f"bf{i}_{j}" for j in range(N_FREQ))
        cf_vars = ", ".join(f"b{i}_c{j}" for j in range(N_FREQ))
        lines.append(f"    {bf_vars} = dft_6_point({cf_vars})")

    # 3. FREQUENCY-DOMAIN MATMUL: for each freq f, C[c]_f = sum_(a,b) A[a]_f * B[b]_f
    lines.append("")
    lines.append("    # --- 3. FREQUENCY-DOMAIN 3x3 MATMUL (6 freqs) ---")
    for f in range(N_FREQ):
        lines.append(f"    # freq {f}")
        for c in range(N_ENTRIES):
            terms = []
            for a, b in matmul_operands(c):
                terms.append(f"af{a}_{f}*bf{b}_{f}")
            lines.append(f"    c{c}_f{f} = fast_mod7({' + '.join(terms)})")

    # 4. IDFT & PACK & STORE
    lines.append("")
    lines.append("    # --- 4. IDFT & PACK & STORE ---")
    for c in range(N_ENTRIES):
        cf_vars = ", ".join(f"c{c}_f{j}" for j in range(N_FREQ))
        r_vars = ", ".join(f"r{c}_c{j}" for j in range(N_FREQ))
        lines.append(f"    {r_vars} = idft_6_point({cf_vars})")
        pack_args = ", ".join(f"r{c}_c{j}" for j in range(N_FREQ))
        lines.append(f"    res{c} = pack_poly({pack_args})")
    for i in range(N_ENTRIES):
        lines.append(f"    tl.store(C_ptr + {i} * n_matrices + offs, res{i}, mask=mask)")

    return "\n".join(lines)


def generate_full_module() -> str:
    body = generate_kernel_body()
    return f'''import torch
import triton
import triton.language as tl

# Generated by gen_unrolled.py — F_7[x]/(x^6-1), SoA (9, Batch). Edit the generator, not this file.


@triton.jit
def fast_mod7(x):
    """Barrett reduction x % 7."""
    q = (x.to(tl.int64) * 74899) >> 19
    q = q.to(tl.int32)
    r = x - q * 7
    r = tl.where(r >= 7, r - 7, r)
    return r


@triton.jit
def unpack_poly(packed):
    """Unpack int32 into 6 coefficients. Returns tuple (c0..c5)."""
    mask = 7
    c0 = packed & mask
    c1 = (packed >> 3) & mask
    c2 = (packed >> 6) & mask
    c3 = (packed >> 9) & mask
    c4 = (packed >> 12) & mask
    c5 = (packed >> 15) & mask
    return c0, c1, c2, c3, c4, c5


@triton.jit
def pack_poly(c0, c1, c2, c3, c4, c5):
    """Pack 6 coefficients into int32."""
    val = c0
    val = val | (c1 << 3)
    val = val | (c2 << 6)
    val = val | (c3 << 9)
    val = val | (c4 << 12)
    val = val | (c5 << 15)
    return val


@triton.jit
def dft_6_point(c0, c1, c2, c3, c4, c5):
    """DFT over F_7, W=3."""
    f0 = fast_mod7(c0 + c1 + c2 + c3 + c4 + c5)
    f1 = fast_mod7(c0*1 + c1*3 + c2*2 + c3*6 + c4*4 + c5*5)
    f2 = fast_mod7(c0*1 + c1*2 + c2*4 + c3*1 + c4*2 + c5*4)
    f3 = fast_mod7(c0*1 + c1*6 + c2*1 + c3*6 + c4*1 + c5*6)
    f4 = fast_mod7(c0*1 + c1*4 + c2*2 + c3*1 + c4*4 + c5*2)
    f5 = fast_mod7(c0*1 + c1*5 + c2*4 + c3*6 + c4*2 + c5*3)
    return f0, f1, f2, f3, f4, f5


@triton.jit
def idft_6_point(f0, f1, f2, f3, f4, f5):
    """Inverse DFT, W^-1=5, scale 6."""
    t0 = fast_mod7(f0 + f1 + f2 + f3 + f4 + f5)
    t1 = fast_mod7(f0*1 + f1*5 + f2*4 + f3*6 + f4*2 + f5*3)
    t2 = fast_mod7(f0*1 + f1*4 + f2*2 + f3*1 + f4*4 + f5*2)
    t3 = fast_mod7(f0*1 + f1*6 + f2*1 + f3*6 + f4*1 + f5*6)
    t4 = fast_mod7(f0*1 + f1*2 + f2*4 + f3*1 + f4*2 + f5*4)
    t5 = fast_mod7(f0*1 + f1*3 + f2*2 + f3*6 + f4*4 + f5*5)
    return fast_mod7(t0*6), fast_mod7(t1*6), fast_mod7(t2*6), fast_mod7(t3*6), fast_mod7(t4*6), fast_mod7(t5*6)


@triton.jit
def ring_matmul_kernel(
    A_ptr, B_ptr, C_ptr,
    n_matrices, BLOCK_SIZE: tl.constexpr
):
    pid = tl.program_id(0)
    offs = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offs < n_matrices

{body}


def ring_matmul(A, B):
    """Batched ring matrix multiplication over F_7[x]/(x^6-1). SoA (9, Batch)."""
    assert A.shape[0] == 9 and B.shape[0] == 9, f"Expected (9, Batch), got A={{A.shape}}, B={{B.shape}}"
    batch_size = A.shape[1]
    C = torch.empty_like(A)
    grid = lambda meta: (triton.cdiv(batch_size, meta['BLOCK_SIZE']),)
    ring_matmul_kernel[grid](A, B, C, n_matrices=batch_size, BLOCK_SIZE=128)
    return C
'''


def main():
    ap = argparse.ArgumentParser(description="Generate unrolled Triton ring matmul kernel")
    ap.add_argument("-o", "--output", help="Write to file instead of stdout")
    args = ap.parse_args()
    out = generate_full_module()
    if args.output:
        with open(args.output, "w") as f:
            f.write(out)
        print(f"Wrote {args.output}", file=__import__("sys").stderr)
    else:
        print(out)


if __name__ == "__main__":
    main()
